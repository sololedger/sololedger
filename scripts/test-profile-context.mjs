import assert from 'node:assert/strict'
import { build } from 'esbuild'
import { chromium, expect } from '@playwright/test'
import { resolve } from 'node:path'
const bundle = await build({ entryPoints: ['tests/fixtures/profileContextHarness.tsx'], bundle: true, write: false,
  platform: 'browser', format: 'iife', jsx: 'automatic', plugins: [{ name: 'synthetic-profile-transport', setup(b) {
    b.onResolve({ filter: /supabaseClient$/ }, () => ({ path: resolve('tests/fixtures/profileContextMocks.ts') }))
  } }] })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage()
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('dialog', d => d.accept())
  await page.route('**/*', route => route.fulfill({ body: '<div id="root"></div>', contentType: 'text/html' }))
  await page.goto('http://127.0.0.1:31040')
  await page.addScriptTag({ content: bundle.outputFiles[0].text })
  await page.waitForFunction(() => window.test)
  const call = (name, ...args) => page.evaluate(([n, a]) => window.test[n](...a), [name, args])
  const state = () => page.locator('#state').textContent().then(JSON.parse)
  const pending = n => expect.poll(() => call('pending').then(p => p.length)).toBe(n)
  const company = name => expect(page.locator('#company-name')).toHaveValue(name)
  const hidden = async () => { await expect(page.locator('#company-name')).toHaveCount(0); assert.equal(await call('book'), false) }
  await call('event', 'A'); await pending(1); await call('finish', 0); await company('Company A')
  const old = await call('capture')
  await call('event', 'A'); await pending(1)
  await call('event', 'B'); await pending(2); await hidden()
  await call('finish', 1); await company('Company B'); await call('finish', 0); await company('Company B')
  assert.equal(await call('verifyOld', old), false)
  console.log('PASS A→B delayed A response, old write closure denied')
  await call('event', 'A'); await call('event', 'B'); await call('event', 'A'); await pending(3)
  await call('finish', 2); await company('Company A'); await call('finish', 1); await call('finish', 0); await company('Company A')
  console.log('PASS A→B→A replies out of order')
  await call('retry'); await call('retry'); await pending(2); await hidden()
  await call('finish', 1, false, { ...await page.evaluate(() => window.test.profiles.A), company_name: 'Newest A' })
  await company('Newest A'); await call('finish', 0); await company('Newest A')
  console.log('PASS concurrent same-owner loads; newest sequence wins')
  await call('retry'); await pending(1); await call('event', null); await call('finish', 0); await hidden()
  console.log('PASS logout during fetch')
  await call('event', 'B'); await pending(1); await call('finish', 0, true); await hidden(); assert.equal((await state()).error, true)
  console.log('PASS profile failure stays closed; no VAT defaults or write')
  await call('retry'); await pending(1); await call('finish', 0); await company('Company B')
  await page.locator('#company-name').fill('B changed name')
  await page.getByRole('button', { name: 'Spara ändringar', exact: true }).click()
  await pending(1); await call('finish', 0); await company('B changed name')
  const writes = await page.evaluate(() => window.test.writes)
  assert.equal(writes.length, 1); assert.equal(writes[0].id, 'B'); assert.equal(writes[0].patch.default_deduction_entitlement, 'none'); assert.equal(writes[0].patch.vat_period_type, 'month')
  assert.equal(await call('book'), true)
  assert.equal((await page.evaluate(() => window.test.bookings)).at(-1).inputVat, 0)
  console.log('PASS normal login, B name save preserves month/none, B booking uses zero input VAT')
  await call('identityMismatch', true); assert.equal(await call('book'), false)
  await call('identityMismatch', false)
  await call('event', 'A'); await pending(1); await call('finish', 0, false, { id: 'B', company_name: 'Wrong owner' }); await hidden()
  assert.equal((await state()).error, true)
  console.log('PASS verified-identity mismatch and wrong-row response deny writes')
  await call('retry'); await pending(1); await call('finish', 0, false, { id: 'A' }); await hidden()
  assert.equal((await state()).error, true)
  console.log('PASS incomplete profile is a failed load, never default VAT settings')
  await call('retry'); await call('retry'); await pending(2)
  await call('finish', 1); await company('Company A'); await call('finish', 0, true); await company('Company A')
  console.log('PASS stale failure cannot replace successful same-owner refresh')
  await call('prepare'); await call('silentOwner', 'B'); assert.equal(await call('dispatchPrepared'), true)
  assert.equal((await page.evaluate(() => window.test.bookings)).at(-1).owner, 'A')
  await call('event', 'B'); await pending(1); await call('finish', 0); await company('B changed name')
  const count = (await page.evaluate(() => window.test.bookings)).length
  assert.equal(await call('dispatchPrepared'), false)
  assert.equal((await page.evaluate(() => window.test.bookings)).length, count)
  console.log('PASS request bearer is pinned; changed generation blocks prepared RPC before transport')
  await call('retry'); await pending(1); await call('unmount'); await call('finish', 0)
  assert.equal(await call('dispatchPrepared'), false)
  console.log('PASS unmount invalidates pending reads and prepared writes')


  assert.deepEqual(errors, [])
} finally { await browser.close() }
